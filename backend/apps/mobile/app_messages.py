APP_MESSAGE_DEFAULTS = {
    field["key"]: field["default_value"]
    for section in APP_MESSAGE_SECTIONS
    for field in section["fields"]
}


def merge_mobile_app_messages(overrides=None):
    merged = dict(APP_MESSAGE_DEFAULTS)
    for key, value in (overrides or {}).items():
        if key in merged and str(value or "").strip():
            merged[key] = str(value).strip()
    return merged


def sanitize_mobile_app_message_overrides(messages=None):
    overrides = {}
    for key, default_value in APP_MESSAGE_DEFAULTS.items():
        raw_value = str((messages or {}).get(key, "") or "").strip()
        if raw_value and raw_value != str(default_value).strip():
            overrides[key] = raw_value
    return overrides
